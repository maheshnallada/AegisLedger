from typing import List
from fastapi import APIRouter, Depends, status
from sqlalchemy.orm import Session
from backend.app.database import get_db
from backend.app.schemas.account import AccountCreate, AccountResponse, AccountBalanceResponse
from backend.app.services.account_service import AccountService

router = APIRouter(prefix="/accounts", tags=["Accounts"])

@router.post("", response_model=AccountResponse, status_code=status.HTTP_201_CREATED)
def create_account(account_in: AccountCreate, db: Session = Depends(get_db)):
    """Create a new account. Initial balance is always 0 and generated by system."""
    return AccountService.create_account(db, account_in)

@router.get("", response_model=List[AccountResponse])
def list_accounts(skip: int = 0, limit: int = 100, db: Session = Depends(get_db)):
    """List all accounts."""
    return AccountService.list_accounts(db, skip=skip, limit=limit)

@router.get("/{account_id}", response_model=AccountResponse)
def get_account(account_id: str, db: Session = Depends(get_db)):
    """Get account details by ID."""
    return AccountService.get_account_by_id(db, account_id)

@router.get("/{account_id}/balance", response_model=AccountBalanceResponse)
def get_account_balance(account_id: str, db: Session = Depends(get_db)):
    """Fetch the current balance of an account."""
    return AccountService.get_account_balance(db, account_id)
